export function getInitialHistoricalPredictions(): PredictionResult[] {
  const now = new Date();
  return RAW_HISTORICAL_CAMPAIGNS.map((item, index) => {
    const { dateOffsetDays, ...campaignInput } = item;
    const result = predictCampaign(campaignInput, true);
    // Custom synthetic historical date
    const date = new Date(now.getTime() - dateOffsetDays * 24 * 60 * 60 * 1000);
    result.id = `hist_${index + 1}`;
    result.created_at = date.toISOString();
    return result;
  });
}
